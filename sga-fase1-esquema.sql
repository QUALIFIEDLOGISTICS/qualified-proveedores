-- Configuración: verla quien opera el SGA o la configuración de almacenes; cambiarla, solo configuración.
do $$
declare t text;
begin
  foreach t in array array['sga_zonas', 'sga_ubicaciones', 'sga_clientes'] loop
    execute format('drop policy if exists %1$s_select on public.%1$s', t);
    execute format('drop policy if exists %1$s_insert on public.%1$s', t);
    execute format('drop policy if exists %1$s_update on public.%1$s', t);
    execute format('create policy %1$s_select on public.%1$s for select using (public.sga_permiso(''stock'', ''almacenconfig'', ''citas''))', t);
    execute format('create policy %1$s_insert on public.%1$s for insert with check (public.sga_permiso(''almacenconfig''))', t);
    execute format('create policy %1$s_update on public.%1$s for update using (public.sga_permiso(''almacenconfig''))', t);
  end loop;
end $$;

-- Operativa: quien tiene el módulo «stock». No hay política de borrado: nada se borra, se anula.
do $$
declare t text;
begin
  foreach t in array array['sga_albaranes', 'sga_partidas', 'sga_movimientos', 'sga_servicios', 'sga_cobros'] loop
    execute format('drop policy if exists %1$s_select on public.%1$s', t);
    execute format('drop policy if exists %1$s_insert on public.%1$s', t);
    execute format('drop policy if exists %1$s_update on public.%1$s', t);
    execute format('create policy %1$s_select on public.%1$s for select using (public.sga_permiso(''stock''))', t);
    execute format('create policy %1$s_insert on public.%1$s for insert with check (public.sga_permiso(''stock''))', t);
    execute format('create policy %1$s_update on public.%1$s for update using (public.sga_permiso(''stock''))', t);
  end loop;
end $$;

